    private void btnScanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnScanActionPerformed
       String directoryText = txtDirectory.getText().trim();

      if (directoryText.isEmpty()) {
          
       JOptionPane.showMessageDialog(this,"Please select a directory first.","No Directory Selected",JOptionPane.WARNING_MESSAGE);
       return;
      }

    Path directory = Path.of(directoryText);

    try {
      lblStatus.setText("Status: Scanning...");
      btnScan.setEnabled(false);

      duplicateGroups = controller.scanDirectory(directory);

      DefaultTableModel model =(DefaultTableModel) tblResults.getModel();
      model.setRowCount(0);
      int groupNumber = 1;

    for (DuplicateGroup<File> group : duplicateGroups) {
        for (File file : group.getFiles()) {
            model.addRow(new Object[]{
            false,
            file.getName(),
            file.getAbsolutePath(),
            String.format("%.2f", file.length() / 1024.0),
            groupNumber});
        }

        groupNumber++;
    }

    lblStatus.setText("Status: Scan complete — " + duplicateGroups.size() + " duplicate groups found.");

    } catch (IOException | IllegalArgumentException ex) {
        
    JOptionPane.showMessageDialog(this,ex.getMessage(),"Scan Failed",JOptionPane.ERROR_MESSAGE);
    lblStatus.setText("Status: Scan failed.");

   } finally {
    btnScan.setEnabled(true);
   }
    }//GEN-LAST:event_btnScanActionPerformed

    private void btnQuarantineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuarantineActionPerformed
     
     DefaultTableModel model = (DefaultTableModel) tblResults.getModel();
     List<File> selectedFiles = new ArrayList<>();

     // Collect the checked files.
    for (int row = 0; row < model.getRowCount(); row++) {
    boolean selected = Boolean.TRUE.equals(model.getValueAt(row, 0));

    if (selected) {
        String filePath = model.getValueAt(row, 2).toString();
        selectedFiles.add(new File(filePath));
        }
    }

    if (selectedFiles.isEmpty()) {
    JOptionPane.showMessageDialog(this,"Please tick at least one file to quarantine.","No Files Selected",JOptionPane.WARNING_MESSAGE);
    return;
    }

    // Count how many files from each duplicate group are selected.
    Map<Integer, Integer> selectedPerGroup = new HashMap<>();
    Map<Integer, Integer> totalPerGroup = new HashMap<>();

    for (int row = 0; row < model.getRowCount(); row++) {
    int groupNumber = Integer.parseInt(model.getValueAt(row, 4).toString());

    totalPerGroup.merge(groupNumber, 1, Integer::sum);

    if (Boolean.TRUE.equals(model.getValueAt(row, 0))) {
        selectedPerGroup.merge(groupNumber, 1, Integer::sum);
    }
    }

     // Never allow every copy in a duplicate group to be quarantined.
     for (Integer groupNumber : selectedPerGroup.keySet()) {
        if (selectedPerGroup.get(groupNumber).equals(totalPerGroup.get(groupNumber))) {    
              JOptionPane.showMessageDialog(this,"You cannot quarantine every file in duplicate group "+ groupNumber + ".\n" + "At least one copy must remain outside quarantine.","Unsafe Operation",JOptionPane.WARNING_MESSAGE);
         return;
        }
      }

      int confirm = JOptionPane.showConfirmDialog( this,"Move " + selectedFiles.size() + " selected file(s) to quarantine?","Confirm Quarantine",JOptionPane.YES_NO_OPTION,JOptionPane.WARNING_MESSAGE);

     if (confirm != JOptionPane.YES_OPTION) {
          return;
        }

    try {
       List<Path> movedFiles = controller.quarantine(selectedFiles);

       JOptionPane.showMessageDialog(this,movedFiles.size() + " file(s) moved to quarantine successfully.","Quarantine Complete",JOptionPane.INFORMATION_MESSAGE);

    
    // Remove successfully quarantined files from the displayed results.
      for (File file : selectedFiles) {
       String originalPath = file.toPath().toAbsolutePath().normalize().toString();

         for (int row = model.getRowCount() - 1; row >= 0; row--) {
           String tablePath = Path.of(
                model.getValueAt(row, 2).toString()
              ).toAbsolutePath().normalize().toString();

        if (originalPath.equals(tablePath)) {
            model.removeRow(row);
            break;
            }
         }
      }

    lblStatus.setText("Status: Quarantine completed.");

    } catch (IOException | IllegalArgumentException ex) {
        
      JOptionPane.showMessageDialog(this,ex.getMessage(),"Quarantine Failed",JOptionPane.ERROR_MESSAGE);
      lblStatus.setText("Status: Quarantine failed.");
      
        }
    }//GEN-LAST:event_btnQuarantineActionPerformed

