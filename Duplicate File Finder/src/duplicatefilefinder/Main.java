    private void btnDeleteSelectedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteSelectedActionPerformed
       DefaultTableModel model = (DefaultTableModel) tblResults.getModel();

    List<File> selectedFiles = new ArrayList<>();

    // Collect checked files.
    for (int row = 0; row < model.getRowCount(); row++) {
        if (Boolean.TRUE.equals(model.getValueAt(row, 0))) {
            String filePath = model.getValueAt(row, 2).toString();
            selectedFiles.add(new File(filePath));
        }
    }

    // Check whether any files were selected.
    if (selectedFiles.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please select at least one file to delete.",
                "No Files Selected",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Count selected files and total files in each duplicate group.
    Map<Integer, Integer> selectedPerGroup = new HashMap<>();
    Map<Integer, Integer> totalPerGroup = new HashMap<>();

    for (int row = 0; row < model.getRowCount(); row++) {
        int groupNumber = Integer.parseInt(
                model.getValueAt(row, 4).toString()
        );

        totalPerGroup.merge(groupNumber, 1, Integer::sum);

        if (Boolean.TRUE.equals(model.getValueAt(row, 0))) {
            selectedPerGroup.merge(groupNumber, 1, Integer::sum);
        }
    }

    // Keep at least one copy outside quarantine.
    for (Integer groupNumber : selectedPerGroup.keySet()) {
        if (selectedPerGroup.get(groupNumber)
                .equals(totalPerGroup.get(groupNumber))) {

            JOptionPane.showMessageDialog(
                    this,
                    "You cannot delete every file in duplicate group "
                            + groupNumber + ".\n"
                            + "At least one copy must remain.",
                    "Unsafe Operation",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }
    }

    // Confirm permanent deletion.
    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Permanently delete " + selectedFiles.size()
                    + " selected file(s)?\n\n"
                    + "This action cannot be undone.",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    // Delete the selected files.
    try {
        int deletedCount = 0;

        for (File file : selectedFiles) {
            if (Files.deleteIfExists(file.toPath())) {
                deletedCount++;
            }
        }

        // Remove deleted files from the results table.
        for (int row = model.getRowCount() - 1; row >= 0; row--) {
            String filePath = model.getValueAt(row, 2).toString();

            for (File file : selectedFiles) {
                String selectedPath = file.toPath()
                        .toAbsolutePath()
                        .normalize()
                        .toString();

                String tablePath = Path.of(filePath)
                        .toAbsolutePath()
                        .normalize()
                        .toString();

                if (selectedPath.equals(tablePath)
                        && !Files.exists(file.toPath())) {
                    model.removeRow(row);
                    break;
                }
            }
        }

        JOptionPane.showMessageDialog(
                this,
                deletedCount + " file(s) permanently deleted.",
                "Deletion Complete",
                JOptionPane.INFORMATION_MESSAGE
        );

        lblStatus.setText("Status: Deletion completed.");

    } catch (IOException | IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Could not delete files: " + ex.getMessage(),
                "Deletion Failed",
                JOptionPane.ERROR_MESSAGE
        );

        lblStatus.setText("Status: Deletion failed.");
    }
    }//GEN-LAST:event_btnDeleteSelectedActionPerformed

    private void menuExportResultsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuExportResultsActionPerformed
       if (duplicateGroups == null || duplicateGroups.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please scan a directory before exporting results.",
            "No Results",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

String[] formats = {"CSV", "JSON"};

int choice = JOptionPane.showOptionDialog(
        this,
        "Choose an export format:",
        "Export Results",
        JOptionPane.DEFAULT_OPTION,
        JOptionPane.QUESTION_MESSAGE,
        null,
        formats,
        formats[0]
);

if (choice == -1) {
    return;
}

JFileChooser fileChooser = new JFileChooser();
fileChooser.setDialogTitle("Save Scan Results");

if (choice == 0) {
    fileChooser.setSelectedFile(new File("duplicate-results.csv"));
} else {
    fileChooser.setSelectedFile(new File("duplicate-results.json"));
}

if (fileChooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
    return;
}

Path outputPath = fileChooser.getSelectedFile().toPath();

try {
    AppController.ExportFormat format =
            choice == 0
                    ? AppController.ExportFormat.CSV
                    : AppController.ExportFormat.JSON;

    controller.exportResults(duplicateGroups, format, outputPath);

    JOptionPane.showMessageDialog(
            this,
            "Results exported successfully to:\n" + outputPath,
            "Export Complete",
            JOptionPane.INFORMATION_MESSAGE
    );

} catch (IOException | IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(
            this,
            "Could not export results:\n" + ex.getMessage(),
            "Export Failed",
            JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_menuExportResultsActionPerformed

